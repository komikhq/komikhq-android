package com.komikhq.app.data.network

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.longOrNull
import okhttp3.ResponseBody
import retrofit2.Converter
import retrofit2.Retrofit
import java.lang.reflect.Type

/**
 * Converter Factory to handle endpoints returning `kotlin.Any` / `java.lang.Object`
 * generated by OpenAPI Generator for unstructured responses (e.g. Better Auth endpoints).
 */
class AnyJsonConverterFactory(
    private val json: Json = Json { ignoreUnknownKeys = true; isLenient = true }
) : Converter.Factory() {

    override fun responseBodyConverter(
        type: Type,
        annotations: Array<out Annotation>,
        retrofit: Retrofit
    ): Converter<ResponseBody, *>? {
        if (type == Any::class.java || type == java.lang.Object::class.java) {
            return Converter<ResponseBody, Any> { body ->
                val string = body.string()
                try {
                    val element = json.parseToJsonElement(string)
                    jsonElementToMap(element)
                } catch (e: Exception) {
                    string
                }
            }
        }
        return null
    }

    private fun jsonElementToMap(element: JsonElement): Any {
        return when (element) {
            is JsonObject -> element.mapValues { (_, value) -> jsonElementToMap(value) }
            is JsonArray -> element.map { jsonElementToMap(it) }
            is JsonPrimitive -> {
                if (element.isString) {
                    element.content
                } else {
                    element.booleanOrNull
                        ?: element.longOrNull
                        ?: element.doubleOrNull
                        ?: element.content
                }
            }
            is JsonNull -> ""
        }
    }
}

